const plannerForm = document.getElementById("planner-form");
const topicInput  = document.getElementById("topic-input");
const generateBtn = document.getElementById("generate-btn");
const loadingEl   = document.getElementById("planner-loading");
const errorEl     = document.getElementById("planner-error");
const resultEl    = document.getElementById("planner-result");

plannerForm.addEventListener("submit", async e => {
  e.preventDefault();
  const topic = topicInput.value.trim();
  if (!topic) return;

  errorEl.classList.add("hidden");
  resultEl.classList.add("hidden");
  loadingEl.classList.remove("hidden");
  generateBtn.disabled = true;

  try {
    const plan = hasApiKey()
      ? await generatePlan(topic)
      : buildDemoPlan(topic);
    renderPlan(plan);
  } catch (err) {
    showError(err.message || "Something went wrong. Please try again.");
  } finally {
    loadingEl.classList.add("hidden");
    generateBtn.disabled = false;
  }
});

// ─── AI API Call (delegates to Flask backend) ───

async function generatePlan(topic) {
  const prov = activeProvider();
  const res = await fetch("/api/learning-plan", {
    method: "POST",
    headers: {
      "Content-Type": "application/json",
    },
    body: JSON.stringify({
      topic,
      provider: SESSION.provider,
      apiKey: SESSION.apiKey,
      model: activeModel(),
      baseUrl: SESSION.baseUrl || prov.defaultBaseUrl,
    }),
  });

  if (!res.ok) {
    const err = await res.json().catch(() => ({}));
    throw new Error(err?.error || `Backend error (${res.status}).`);
  }

  const data = await res.json();
  if (data.error) {
    throw new Error(data.error);
  }
  return data;
}

